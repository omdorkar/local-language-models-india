"""Check which Indian languages in Belebele have romanized (English-letter) versions, and that they are
truly parallel to the native-script versions: same items, same correct answers, actually in Latin script.

    python -m evaluation.inspect_belebele   # writes reports/belebele_scripts.{md,json}
"""

import json
import unicodedata

import pandas as pd

from . import DATA_RAW, REPORTS
from .config import LANGUAGES

BELEBELE = DATA_RAW / "belebele" / "data"


def load(config: str) -> pd.DataFrame:
    df = pd.read_json(BELEBELE / f"{config}.jsonl", lines=True, dtype={"correct_answer_num": str})
    return df.set_index(["link", "question_number"]).sort_index()


def latin_share(texts: pd.Series) -> float:
    """Fraction of alphabetic characters that are Latin script."""
    letters = [c for t in texts for c in t if c.isalpha()]
    latin = sum(unicodedata.name(c, "").startswith("LATIN") for c in letters)
    return latin / len(letters) if letters else 0.0


def main() -> None:
    english = load("eng_Latn")
    rows, samples = [], {}
    for code, lang in LANGUAGES.items():
        if code == "en" or not lang.belebele_native:
            continue
        native = load(lang.belebele_native)
        row = {
            "language": lang.name,
            "native_config": lang.belebele_native,
            "native_items": len(native),
            "native_latin_share": round(latin_share(native.flores_passage), 3),
            "parallel_to_english": bool(native.index.equals(english.index)),
            "answers_match_english": bool((native.correct_answer_num == english.correct_answer_num).all()),
            "romanized_config": lang.belebele_latn,
        }
        if lang.belebele_latn:
            latn = load(lang.belebele_latn)
            row |= {
                "romanized_items": len(latn),
                "romanized_latin_share": round(latin_share(latn.flores_passage), 3),
                "romanized_parallel_to_native": bool(latn.index.equals(native.index)),
                "romanized_answers_match_native": bool((latn.correct_answer_num == native.correct_answer_num).all()),
            }
            first = native.index[0]
            samples[lang.name] = {
                "native_question": native.loc[first, "question"],
                "romanized_question": latn.loc[first, "question"],
                "english_question": english.loc[first, "question"],
            }
        rows.append(row)

    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "belebele_scripts.json").write_text(
        json.dumps({"languages": rows, "samples": samples}, indent=2, ensure_ascii=False))

    table = pd.DataFrame(rows).astype({"romanized_items": "Int64"})
    roman = table[table.romanized_config.notna()]
    lines = [
        "# Belebele: native vs. romanized coverage for Indian languages",
        "",
        "Generated by `python -m evaluation.inspect_belebele` from the files in `data/raw/belebele`.",
        "Per the Belebele paper (§3), romanized passages were transliterated by annotators with IndicXlit support,",
        "so they are human-checked rather than raw machine output.",
        "",
        f"- Indian-language configs found: **{len(table)}** native-script, **{len(roman)}** romanized "
        f"({', '.join(roman.language)}).",
        f"- All native configs parallel to English (same items, same answers): "
        f"**{bool(table.parallel_to_english.all() and table.answers_match_english.all())}**",
        f"- All romanized configs parallel to their native version: "
        f"**{bool(roman.romanized_parallel_to_native.all() and roman.romanized_answers_match_native.all())}**",
        "",
        table.astype(object).where(table.notna(), "—").to_markdown(index=False),
        "",
        "## Same item, three ways",
        "",
    ]
    for name, s in samples.items():
        lines += [f"**{name}**", "",
                  f"- English: {s['english_question']}",
                  f"- Native: {s['native_question']}",
                  f"- Romanized: {s['romanized_question']}", ""]
    (REPORTS / "belebele_scripts.md").write_text("\n".join(lines))
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
